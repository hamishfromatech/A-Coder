#!/usr/bin/env node
// Generates `common/modelCatalog.generated.ts` from https://models.dev/api.json.
//
// The catalog gives the IDE per-model contextWindow + maxOutputTokens data for
// providers where our hand-written tables in modelCapabilities.ts are incomplete
// (same data source a-coder-cli uses for its generated model catalog).
//
// Usage (from this directory):
//   node scripts/generate-model-catalog.mjs
//
// Run manually to refresh; the output is checked in. This script is plain Node
// ESM (Node 22+) so it never goes through the VS Code tsc build.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = join(SCRIPT_DIR, '..', 'common', 'modelCatalog.generated.ts');
const MODELS_DEV_URL = 'https://models.dev/api.json';

// models.dev provider id -> A-Coder IDE ProviderName(s).
// ollama / ollamaCloud are intentionally absent: their context windows come from
// the runtime probe (refreshModelService -> tokenCountingService dynamic cache).
const PROVIDER_MAP = {
	anthropic: ['anthropic'],
	openai: ['openAI'],
	google: ['gemini', 'googleVertex'],
	xai: ['xAI'],
	deepseek: ['deepseek'],
	groq: ['groq'],
	mistral: ['mistral'],
	openrouter: ['openRouter'],
};

async function main() {
	console.log(`Fetching ${MODELS_DEV_URL} ...`);
	const res = await fetch(MODELS_DEV_URL);
	if (!res.ok) {
		throw new Error(`Failed to fetch models.dev: ${res.status} ${res.statusText}`);
	}
	const api = JSON.parse(await res.text());

	/** @type {{ [ideProvider: string]: { [modelId: string]: { contextWindow: number; maxTokens: number } } }} */
	const catalog = {};
	let included = 0;
	let skipped = 0;

	for (const [modelsDevProvider, ideProviders] of Object.entries(PROVIDER_MAP)) {
		const providerEntry = api[modelsDevProvider];
		if (!providerEntry?.models) {
			console.warn(`  ! provider "${modelsDevProvider}" not found on models.dev, skipping`);
			continue;
		}
		const modelEntries = Object.entries(providerEntry.models);
		for (const ideProvider of ideProviders) {
			catalog[ideProvider] ??= {};
		}
		for (const [modelId, model] of modelEntries) {
			const contextWindow = model?.limit?.context;
			const maxTokens = model?.limit?.output;
			if (typeof contextWindow !== 'number' || contextWindow <= 0 ||
				typeof maxTokens !== 'number' || maxTokens <= 0) {
				skipped++;
				continue;
			}
			for (const ideProvider of ideProviders) {
				// keep the first (canonical) entry per model id; models.dev already dedupes
				catalog[ideProvider][modelId] = { contextWindow, maxTokens };
			}
			included++;
		}
	}

	// deterministic output: sort providers, then model ids
	const sortedCatalog = {};
	for (const provider of Object.keys(catalog).sort()) {
		const models = {};
		for (const modelId of Object.keys(catalog[provider]).sort()) {
			models[modelId] = catalog[provider][modelId];
		}
		sortedCatalog[provider] = models;
	}

	const ts = `// This file is auto-generated by scripts/generate-model-catalog.mjs
// Do not edit manually - run: node scripts/generate-model-catalog.mjs
//
// Source: https://models.dev/api.json (fetched ${new Date().toISOString()})
// Only models that specify both limit.context and limit.output are included.
// modelCapabilities.ts consults this as a FALLBACK - hand-written tables there always win.

export type GeneratedModelCatalog = {
	[provider: string]: { [modelId: string]: { contextWindow: number; maxTokens: number } }
}

export const generatedModelCatalog = ${JSON.stringify(sortedCatalog, null, '\t')} satisfies GeneratedModelCatalog
`;

	mkdirSync(dirname(OUT_PATH), { recursive: true });
	writeFileSync(OUT_PATH, ts);

	const perProvider = Object.entries(sortedCatalog)
		.map(([p, m]) => `${p}: ${Object.keys(m).length}`)
		.join(', ');
	console.log(`Wrote ${OUT_PATH}`);
	console.log(`Included ${included} models (${skipped} skipped for missing limits): ${perProvider}`);
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});